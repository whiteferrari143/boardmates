import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.resolve('wrangler/package.json'));
await require('esbuild').build({entryPoints:['lib/games/spyfall.ts'],bundle:true,format:'esm',platform:'node',outfile:'.sites-runtime/spyfall-test.mjs'});
const {spyfall:g,tickSpyfall}=await import('../.sites-runtime/spyfall-test.mjs');
let checks=0;const ok=(c,m)=>{assert.ok(c,m);checks++;console.log(`✓ ${m}`);};
const ctx={playerIds:Array.from({length:12},(_,i)=>`p${i}`),hostId:'p0'};
const run=(s,a,id='p0',c=ctx)=>{assert.ok(g.validateAction(s,a,id,c),`Action ${a.type} from ${id}`);return g.updateState(s,a,id,c);};
const newGame=()=>{let s=g.createInitialState(ctx);run(s,{type:'begin'});return s;};
const ready=s=>s.players.forEach(id=>run(s,{type:'seen'},id));
const ids=s=>({spies:s.players.filter(p=>s.secrets[p].spy),locals:s.players.filter(p=>!s.secrets[p].spy)});
const vote=(s,yes)=>{for(const id of s.players.filter(id=>id!==s.vote.target))run(s,{type:'vote',yes},id);};
let s=newGame();let {spies,locals}=ids(s);
ok(spies.length===2&&new Set(locals.map(id=>s.secrets[id].role)).size===10,'12 players have 2 spies and 10 distinct positions');
const hidden=g.getPlayerView(s,spies[0],ctx),known=g.getPlayerView(s,locals[0],ctx);
ok(hidden.location===null&&hidden.scenario===null&&hidden.revealed===null&&!('secrets' in hidden)&&!('history' in hidden),'Spy response excludes chosen location, scenario, all other roles and history');
ok(known.location&&known.myRole.role&&!('secrets' in known),'Local sees only their own role and shared location');
ok(hidden.locations.length===30,'All 30 location candidates available without marking answer');
ok(!g.validateAction(s,{type:'begin'},'p1',ctx),'Only host can deal');
ok(!g.validateAction(s,{type:'guess-start'},spies[0],ctx),'Spy cannot guess before everyone is ready');
ready(s);ok(s.phase==='discuss'&&s.deadline>Date.now(),'Clock starts only after all 12 ready');
ok(!g.validateAction(s,{type:'seen'},locals[0],ctx),'Duplicate ready cannot alter phase');
run(s,{type:'ask',target:'p1'});ok(!g.validateAction(s,{type:'answered'},'p2',ctx),'Only current target can complete their answer');
run(s,{type:'answered'},'p1');ok(!g.validateAction(s,{type:'ask',target:'p0'},'p1',ctx),'No immediate return question');
ok(!g.validateAction(s,{type:'ask',target:'p2'},'p0',ctx),'Only current asker can select target');
run(s,{type:'accuse',target:spies[0]},locals[0]);
ok(!g.validateAction(s,{type:'guess-start'},spies[0],ctx),'Spy cannot escape by guessing during vote');
ok(!g.validateAction(s,{type:'vote',yes:true},spies[0],ctx),'Accused player cannot vote');
run(s,{type:'vote',yes:true},locals[0]);
ok(!g.validateAction(s,{type:'vote',yes:false},locals[0],ctx),'Ballot cannot be changed or submitted twice');
const others=s.players.filter(id=>id!==spies[0]&&id!==locals[0]);others.forEach((id,i)=>run(s,{type:'vote',yes:i<9},id));
ok(s.phase==='result'&&s.winner==='locals','10 of 11 eligible votes convict with two spies');
ok(s.awards[locals[0]]===2&&s.awards[spies[1]]===1&&s.awards[spies[0]]===0,'Accuser bonus and uncaught second spy scoring');
ok(g.getPlayerView(s,locals[0],ctx).revealed[spies[0]].spy,'All roles revealed only after result');
const old=s.location;run(s,{type:'next'});ok(s.location!==old&&s.round===2,'Next round avoids previous location');
s=newGame();ready(s);({spies,locals}=ids(s));run(s,{type:'accuse',target:locals[1]},locals[0]);vote(s,true);
ok(s.winner==='spies'&&spies.every(id=>s.awards[id]===4),'Wrong conviction awards spies 4 each');
s=newGame();ready(s);({spies,locals}=ids(s));run(s,{type:'accuse',target:spies[0]},locals[0]);vote(s,false);
ok(s.phase==='discuss'&&s.deadline>Date.now(),'Failed accusation resumes paused clock');
ok(!g.validateAction(s,{type:'accuse',target:spies[1]},locals[0],ctx),'One accusation per player per round');
ok(!g.validateAction(s,{type:'guess-start'},locals[0],ctx),'Locals cannot expose themselves as spies');
run(s,{type:'guess-start'},spies[0]);ok(!g.validateAction(s,{type:'guess',location:s.location},spies[1],ctx),'Second spy waits for first guess');
const wrong=g.getPlayerView(s,spies[0],ctx).locations.find(l=>l.id!==s.location).id;
run(s,{type:'guess',location:wrong},spies[0]);run(s,{type:'guess',location:s.location},spies[1]);
ok(s.winner==='spies'&&s.awards[spies[0]]===2&&s.awards[spies[1]]===4,'One correct guess wins team; only correct spy gets bonus');
s=newGame();ready(s);({spies}=ids(s));run(s,{type:'guess-start'},spies[0]);tickSpyfall(s,ctx,s.deadline+1);
ok(s.phase==='guess'&&g.getPlayerView(s,spies[1],ctx).guessTurn===spies[1],'First spy timeout still gives second spy a chance');
tickSpyfall(s,ctx,s.deadline+1);ok(s.winner==='locals','Both spy guesses timing out loses');
s=newGame();ready(s);tickSpyfall(s,ctx,s.deadline+1);
ok(s.phase==='vote'&&s.vote.final,'Discussion timeout enters final voting, not immediate spy victory');
for(let i=0;i<12;i++)tickSpyfall(s,ctx,s.deadline+1);
ok(s.phase==='result'&&s.winner==='spies','No conviction after all final ballots gives spies victory');
s=newGame();ready(s);tickSpyfall(s,{...ctx,playerIds:ctx.playerIds.slice(1)});
ok(s.winner==='cancelled'&&Object.values(s.scores).every(n=>n===0),'Leaving mid-round cancels without awards');
const small={hostId:'a',playerIds:['a','b','c']};s=g.createInitialState(small);
ok(s.settings.spies===1&&!g.validateAction(s,{type:'configure',settings:{...s.settings,spies:2}},'a',small),'Small group uses one spy');
ok(!g.validateAction(s,{type:'configure',settings:{...s.settings,packs:[]}},'a',small),'At least one location pack required');
run(s,{type:'configure',settings:{...s.settings,rounds:1,packs:['thai'],scenario:false}},'a',small);run(s,{type:'begin'},'a',small);
ok(s.scenario===''&&g.getPlayerView(s,'a',small).locations.length===10,'Pack filter and scenario toggle apply');
small.playerIds.forEach(id=>run(s,{type:'seen'},id,small));let spy=small.playerIds.find(id=>s.secrets[id].spy),local=small.playerIds.find(id=>!s.secrets[id].spy);
run(s,{type:'accuse',target:spy},local,small);small.playerIds.filter(id=>id!==spy).forEach(id=>run(s,{type:'vote',yes:true},id,small));
ok(g.isFinished(s),'One-round match marks room finished');
console.log(`PASS ${checks} Spyfall rule and privacy checks`);
